import {readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {msToFrames, readJson, toIdentifier} from './lib.mjs';

const videosRoot = path.resolve('videos');
const output = path.resolve('apps/remotion/src/generated/video-registry.tsx');
const videoEntries = (await readdir(videosRoot, {withFileTypes: true}))
  .filter((entry) => entry.isDirectory())
  .sort((a, b) => a.name.localeCompare(b.name));

const imports = [
  "import React from 'react';",
  "import {Composition, Folder} from 'remotion';",
  "import {TimelineOverlay} from '../TimelineOverlay';",
  "import type {TimelineComponent} from '../TimelineOverlay';",
];
const definitions = [];
const folders = [];
let importIndex = 0;

for (const videoEntry of videoEntries) {
  const videoDirectory = path.join(videosRoot, videoEntry.name);
  const video = await readJson(path.join(videoDirectory, 'video.json'));
  const anchors = await readJson(path.join(videoDirectory, 'anchors.json'));
  const timeline = await readJson(path.join(videoDirectory, 'timeline.json'));
  const animationsDirectory = path.join(videoDirectory, 'animations');
  const animationEntries = (await readdir(animationsDirectory, {withFileTypes: true}))
    .filter((entry) => entry.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name));
  const componentPairs = [];
  const compositionRows = [];

  for (const animationEntry of animationEntries) {
    const animationDirectory = path.join(animationsDirectory, animationEntry.name);
    const animation = await readJson(path.join(animationDirectory, 'animation.json'));
    const identifier = `Animation${importIndex}${toIdentifier(animation.id)}`;
    importIndex += 1;
    imports.push(
      `import ${identifier} from '../../../../videos/${video.id}/animations/${animation.id}/Composition';`,
    );
    componentPairs.push(`  ${JSON.stringify(animation.id)}: ${identifier},`);
    compositionRows.push(`      <Composition
        id=${JSON.stringify(`Video-${video.id}-${animation.id}`)}
        component={${identifier}}
        width={${video.width}}
        height={${video.height}}
        fps={${video.fps}}
        durationInFrames={${msToFrames(animation.durationMs, video.fps)}}
        defaultProps={${JSON.stringify(animation.defaultProps)}}
      />`);
  }

  const videoIdentifier = toIdentifier(video.id);
  definitions.push(`const ${videoIdentifier}Components: Record<string, TimelineComponent> = {
${componentPairs.join('\n')}
};

const ${videoIdentifier}Overlay: React.FC = () => (
  <TimelineOverlay
    anchors={${JSON.stringify(anchors)}}
    audio={${JSON.stringify(video.audio)}}
    components={${videoIdentifier}Components}
    timeline={${JSON.stringify(timeline)}}
  />
);`);

  folders.push(`    <Folder name=${JSON.stringify(`V-${video.id}`)}>
${compositionRows.join('\n')}
      <Composition
        id=${JSON.stringify(`Video-${video.id}-Overlay`)}
        component={${videoIdentifier}Overlay}
        width={${video.width}}
        height={${video.height}}
        fps={${video.fps}}
        durationInFrames={${msToFrames(video.durationMs, video.fps)}}
      />
    </Folder>`);
}

const source = `/* Generated by scripts/generate-registry.mjs. Do not edit manually. */
${imports.join('\n')}

${definitions.join('\n\n')}

export const GeneratedVideoCompositions: React.FC = () => (
  <>
${folders.join('\n')}
  </>
);
`;

await writeFile(output, source, 'utf8');
console.log(`Generated ${path.relative(process.cwd(), output)} for ${videoEntries.length} video(s)`);

